import { api, getToken } from '../api.js';
import { API_BASE } from '../config.js';

// BloomFlex V2 — 3-day auto planner (draft → validate → publish).
const q = (o) => Object.entries(o).filter(([, v]) => v != null && v !== '')
  .map(([k, v]) => encodeURIComponent(k) + '=' + encodeURIComponent(v)).join('&');

export const autoPlannerApi = {
  // → { from, days, dates[], available, machines:[{ id, code, name, departmentId, departmentName,
  //      days:[{ date, source, windows:[{shift, from, to, startMin, endMin, overnight}], capacityMinutes, text }] }],
  //      jobs:[{ id, so, customer, specCode, departmentName, stageSeq, machineId, planDate, shift,
  //              startAbs, endAbs, startTime, endTime, overnight, plannedQty, estMinutes, planStatus, autoGenerated }],
  //      metrics:{ readySos, drafts, published, capacityMinutes, usedMinutes, usagePct } }
  board: (from, days = 3, department) => api('/api/planning/auto/board?' + q({ from, days, department })),
  // body { from, days, priority: 'FIFO'|'DUE', departmentId? } → { created, replacedDrafts, segments[], unplaced:[{so, stage, department, reason, remainingQty}] }
  generate: (body) => api('/api/planning/auto/generate', { method: 'POST', body }),
  clear: (from, days = 3) => api('/api/planning/auto/clear', { method: 'POST', body: { from, days } }),
  sheet: (from, days = 3, department) => api('/api/planning/auto/sheet?' + q({ from, days, department })),

  /**
   * Publish the drafts in the window. A refused publish answers 409 with every problem
   * in `errors`; api() keeps only the message, so this call reads the body itself and
   * throws an Error carrying `.errors` (list of { jobId, so, machine, date, message }).
   */
  publish: async (from, days = 3) => {
    const headers = { 'Content-Type': 'application/json' };
    const token = getToken();
    if (token) headers.Authorization = 'Bearer ' + token;
    const res = await fetch(API_BASE + '/api/planning/auto/publish', { method: 'POST', headers, body: JSON.stringify({ from, days }) });
    if (res.status === 401) {
      // Same as the shared client: drop the token and bounce to login.
      try { localStorage.removeItem('blm_token'); } catch { /* storage blocked */ }
      window.dispatchEvent(new CustomEvent('auth:expired'));
      const err = new Error('Session expired — please sign in again.'); err.status = 401; throw err;
    }
    if (!res.ok) {
      let body = {};
      try { body = await res.json(); } catch { /* not JSON */ }
      const err = new Error(body.message || body.error || body.detail
        || (res.status === 409 ? 'The draft cannot be published' : 'HTTP ' + res.status));
      err.status = res.status;
      if (res.status === 409) err.code = 'conflict';
      else if (res.status === 403) err.code = 'forbidden';
      err.errors = Array.isArray(body.errors) ? body.errors : [];
      throw err;
    }
    return res.json();
  },
};

/** "HH:mm" for minutes past midnight of the plan date (wraps past 24:00). */
export function hhmm(min) {
  const m = ((Number(min) % 1440) + 1440) % 1440;
  return String(Math.floor(m / 60)).padStart(2, '0') + ':' + String(m % 60).padStart(2, '0');
}

/** Save text as a file (no-op where the browser cannot, e.g. tests). */
export function saveText(text, filename, type = 'text/csv;charset=utf-8') {
  try {
    if (typeof URL === 'undefined' || typeof URL.createObjectURL !== 'function') return false;
    const url = URL.createObjectURL(new Blob([text], { type }));
    const a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click(); a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    return true;
  } catch { return false; }
}
